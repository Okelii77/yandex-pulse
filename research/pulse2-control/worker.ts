// Isolated RC control plane. No production DB or routes modified.
type DB={prepare(sql:string):any;batch(statements:any[]):Promise<any[]>};
type Env={DB:DB;RC_LOCAL_ONLY?:string;LOCAL_TOKEN?:string;RC_ENABLE_DISPATCH?:string;RC_GITHUB_TOKEN?:string;RC_ORIGIN?:string};
const SLOT=1800000,LEASE=600000,DAY=86400000;
const epoch=(now:number)=>Math.floor(now/SLOT)*SLOT;
const iso=(now:number)=>new Date(now).toISOString();
const response=(body:any,status=200,headers:Record<string,string>={})=>new Response(status===304?null:JSON.stringify(body),{status,headers:{"Content-Type":"application/json;charset=utf-8","Cache-Control":"no-store","X-Content-Type-Options":"nosniff",...headers}});
const utc = (value: any) => typeof value === "string" && /^20\d{2}-\d\d-\d\dT\d\d:\d\d:\d\d/.test(value)
  && Number.isFinite(Date.parse(value));
const idOk = (value: any) => typeof value === "string" && /^[a-z][a-z0-9_-]{0,62}$/.test(value);
const limited = (value: any, max=160) => typeof value === "string" ? value.slice(0,max) : "";
const numberOrNull = (n: any) => Number.isFinite(n) && n >= 0 ? Math.round(n) : null;
const allowedStates = new Set(["ok","degraded","down","no_data","not_configured","disabled","cooldown","unknown"]);

// Do not trust a runner to decide which fields appear in a PUBLIC status JSON.
function safeStatus(input: any) {
  if (!input || !utc(input.generated_at) || !Array.isArray(input.results) ||
      !Array.isArray(input.checks) || !Array.isArray(input.categories) ||
      input.results.length > 150 || input.checks.length > 150 || input.categories.length > 30)
    throw new Error("invalid_snapshot");
  const categories = input.categories.filter((x: any)=>idOk(x.id)).map((x: any)=>({
    id:x.id,title:limited(x.title,80),description:limited(x.description,180),icon:limited(x.icon,32)
  }));
  const checks = input.checks.filter((x: any)=>idOk(x.id)&&idOk(x.category)).map((x: any)=>({
    id:x.id,category:x.category,name:limited(x.name,120),detail:limited(x.detail,240),
    kind:limited(x.kind,40),
    ...(typeof x.url === "string" && /^https:\/\/[a-z0-9.-]+\/[^@]*$/i.test(x.url) &&
       !/[?&#]/.test(x.url) ? {url: limited(x.url,250)} : {})
  }));
  const ids = new Set(checks.map((x: any)=>x.id));
  const results = input.results.filter((x: any)=>ids.has(x.id) && allowedStates.has(x.status) && utc(x.checked_at))
    .map((x: any)=>{
      const row: Record<string, any> = {
        id:x.id,status:x.status,checked_at:x.checked_at,
        latency_ms:numberOrNull(x.latency_ms)
      };
      for (const prop of ["http_code","grpc_code","error_code","last_http_code","last_error_code"]) {
        if (Number.isInteger(x[prop]) && x[prop] >= 0 && x[prop] < 99999999999) row[prop]=x[prop];
      }
      // Reason/note are generated by our code from safe fixed strings. Keep short.
      for(const prop of ["reason","note","transport"]) {
        if(typeof x[prop]==="string") row[prop]=limited(x[prop],180);
      }
      if(utc(x.retry_after_at)) row.retry_after_at=x.retry_after_at;
      return row;
    });
  if(results.length !== input.results.length || results.length !== checks.length)
    throw new Error("incomplete_snapshot");
  return {
    schema:1,generated_at:input.generated_at,
    interval_minutes:30,
    scope:"Synthetic probes from GitHub Actions; NOT official Yandex service status.",
    categories,checks,results
  };
}


const b64url = (input: string) => {
  const str=input.replace(/-/g,"+").replace(/_/g,"/");
  const decoded=atob(str+"=".repeat((4-str.length%4)%4));
  return Uint8Array.from(decoded,c=>c.charCodeAt(0));
};
async function githubOidcValid(token: string, audience="yandex-pulse-rc-ingest", workflow="pulse2-rc-dispatch.yml") {
  try {
    if(!token || token.length>12000)return false;
    const parts=token.split(".");
    if(parts.length!==3)return false;
    const header=JSON.parse(new TextDecoder().decode(b64url(parts[0])));
    const claims=JSON.parse(new TextDecoder().decode(b64url(parts[1])));
    const seconds=Math.floor(Date.now()/1000);
    if(header.alg!=="RS256"||!header.kid||!Number.isInteger(claims.exp)||
       claims.exp<=seconds||claims.exp>seconds+600 ||
       claims.nbf>seconds || claims.iat>seconds+30 ||
       claims.iss!=="https://token.actions.githubusercontent.com" ||
       claims.aud!==audience ||
       claims.repository!=="Okelii77/yandex-pulse" ||
       String(claims.repository_id)!=="1427282907" ||
       claims.ref!=="refs/heads/research/pulse-architecture-20261128" ||
       claims.workflow_ref!==`Okelii77/yandex-pulse/.github/workflows/${workflow}@refs/heads/research/pulse-architecture-20261128`)
      return false;
    const response=await fetch("https://token.actions.githubusercontent.com/.well-known/jwks",{
      cache:'no-store'
    });
    if(!response.ok)return false;
    const jwks:any=await response.json();
    const jwk=(jwks.keys||[]).find((x: any)=>x.kid===header.kid&&x.kty==="RSA"&&x.use==="sig");
    if(!jwk)return false;
    const key=await crypto.subtle.importKey("jwk",jwk,{name:"RSASSA-PKCS1-v1_5",hash:"SHA-256"},false,["verify"]);
    const signed=new TextEncoder().encode(parts[0]+"."+parts[1]);
    return crypto.subtle.verify({name:"RSASSA-PKCS1-v1_5"},key,b64url(parts[2]),signed);
  }catch{return false;}
}


export async function acquire(db:DB,now:number){
 const slot=epoch(now),token=crypto.randomUUID();
 const row=await db.prepare("INSERT INTO rc_lease(slot,token,expires,state) SELECT ?,?,?,'running' WHERE NOT EXISTS(SELECT 1 FROM rc_latest WHERE slot>=?) AND NOT EXISTS(SELECT 1 FROM rc_lease WHERE state='running' AND expires>? AND slot!=?) ON CONFLICT(slot) DO UPDATE SET token=excluded.token,expires=excluded.expires,state='running' WHERE rc_lease.state!='done' AND rc_lease.expires<=? RETURNING token").bind(slot,token,now+LEASE,slot,now,slot,now).first();
 return row?{slot,token}:null;
}
export async function publish(db:DB,claim:{slot:number;token:string},input:any,now:number){
 const data=safeStatus(input);
 if(data.checks.length!==34||new Set(data.checks.map((x:any)=>x.id)).size!==34||new Set(data.results.map((x:any)=>x.id)).size!==34)throw Error("catalog_incomplete");
 if(!Number.isSafeInteger(claim.slot)||typeof claim.token!=="string"||claim.slot!==epoch(claim.slot)||Date.parse(data.generated_at)<claim.slot||Date.parse(data.generated_at)>now+60000)throw Error("invalid_observation");
 if(data.results.some((x:any)=>Date.parse(x.checked_at)>Date.parse(data.generated_at)+60000))throw Error("future_component");
 const measured=data.results.filter((x:any)=>["ok","down","degraded","no_data"].includes(x.status)).map((x:any)=>[x.id,x.checked_at,x.status,x.latency_ms]);
 const guard="EXISTS(SELECT 1 FROM rc_lease WHERE slot=? AND token=? AND state='running' AND expires>?) AND EXISTS(SELECT 1 FROM rc_latest WHERE id=1 AND slot=? AND token=?)";
 const args=[claim.slot,claim.token,now,claim.slot,claim.token];
 const b=await db.batch([
 db.prepare("INSERT INTO rc_latest(id,revision,slot,token,generated_at,payload) SELECT 1,1,?,?,?,? WHERE EXISTS(SELECT 1 FROM rc_lease WHERE slot=? AND token=? AND state='running' AND expires>?) ON CONFLICT(id) DO UPDATE SET revision=rc_latest.revision+1,slot=excluded.slot,token=excluded.token,generated_at=excluded.generated_at,payload=excluded.payload WHERE excluded.slot>rc_latest.slot AND excluded.generated_at>rc_latest.generated_at").bind(claim.slot,claim.token,data.generated_at,JSON.stringify(data),claim.slot,claim.token,now),
 db.prepare("INSERT OR IGNORE INTO rc_samples(check_id,checked_at,status,latency_ms) SELECT json_extract(value,'$[0]'),json_extract(value,'$[1]'),json_extract(value,'$[2]'),json_extract(value,'$[3]') FROM json_each(?) WHERE "+guard).bind(JSON.stringify(measured),...args),
 db.prepare("UPDATE rc_lease SET state='done' WHERE slot=? AND token=? AND "+guard).bind(claim.slot,claim.token,...args),
 ]);
 return b[0].meta.changes===1;
}
export async function maintenance(db:DB,now:number){await db.batch([db.prepare("DELETE FROM rc_samples WHERE checked_at<?").bind(iso(now-90*DAY)),db.prepare("DELETE FROM rc_history WHERE epoch<?").bind(epoch(now)-4*SLOT),db.prepare("DELETE FROM rc_history_lock WHERE expires<=?").bind(now),db.prepare("DELETE FROM rc_lease WHERE slot<? AND expires<=?").bind(epoch(now)-7*DAY,now)]);}
export async function history(db:DB,request:Request,now:number,headers:Record<string,string>={}){
 const latest=await db.prepare("SELECT revision FROM rc_latest WHERE id=1").first();if(!latest)return response({error:"waiting"},503,headers);
 const e=epoch(now),revision=latest.revision+"-"+e,tag='"h-'+revision+'"';
 if(request.headers.get("If-None-Match")===tag)return response(null,304,{...headers,ETag:tag});
 let cached=await db.prepare("SELECT payload FROM rc_history WHERE revision=?").bind(revision).first();
 if(!cached){
  const token=crypto.randomUUID(),lock=await db.prepare("INSERT INTO rc_history_lock VALUES(?,?,?) ON CONFLICT(revision) DO UPDATE SET token=excluded.token,expires=excluded.expires WHERE rc_history_lock.expires<=? RETURNING token").bind(revision,token,now+30000,now).first();
  if(!lock)return response({error:"history_building"},503,{...headers,"Retry-After":"1"});
  try{
   // Double-check after obtaining the lock, avoiding a repeated full scan.
   cached=await db.prepare("SELECT payload FROM rc_history WHERE revision=?").bind(revision).first();
   if(!cached){
    const q=await db.prepare("WITH ranked AS (SELECT *,ROW_NUMBER() OVER(PARTITION BY check_id,CASE WHEN checked_at>=? THEN 'r'||CAST(strftime('%s',checked_at)/1800 AS INT) WHEN checked_at>=? THEN 'w'||CAST(strftime('%s',checked_at)/7200 AS INT) ELSE 'm'||CAST(strftime('%s',checked_at)/21600 AS INT) END ORDER BY CASE status WHEN 'down' THEN 0 WHEN 'degraded' THEN 1 ELSE 2 END,checked_at DESC) rn FROM rc_samples WHERE checked_at>=? AND checked_at<=?) SELECT check_id,checked_at,status,latency_ms FROM ranked WHERE rn=1 ORDER BY check_id,checked_at").bind(iso(e-DAY),iso(e-7*DAY),iso(e-30*DAY),iso(now+60000)).all();
    const series:Record<string,any[]>={};for(const r of q.results)(series[r.check_id]??=[]).push([r.checked_at,r.status,r.latency_ms]);
    const payload=JSON.stringify({schema:1,retention_days:30,revision,as_of:iso(e),series});
    // Fencing checks both source revision and history lease, not merely lock ownership at start.
    await db.prepare("INSERT OR IGNORE INTO rc_history(revision,epoch,source_rev,payload) SELECT ?,?,?,? WHERE EXISTS(SELECT 1 FROM rc_latest WHERE revision=?) AND EXISTS(SELECT 1 FROM rc_history_lock WHERE revision=? AND token=? AND expires>?)").bind(revision,e,latest.revision,payload,latest.revision,revision,token,now).run();
    cached=await db.prepare("SELECT payload FROM rc_history WHERE revision=?").bind(revision).first();
   }
  }finally{await db.prepare("DELETE FROM rc_history_lock WHERE revision=? AND token=?").bind(revision,token).run();}
  if(!cached)return response({error:"revision_changed"},503,{...headers,"Retry-After":"1"});
 }
 const full=JSON.parse(cached.payload),since=new URL(request.url).searchParams.get("since");
 if(since&&since!==revision&&/^\d+-\d+$/.test(since)){
  const old=await db.prepare("SELECT payload FROM rc_history WHERE revision=?").bind(since).first();
  if(old){const prev=JSON.parse(old.payload).series,replace:Record<string,any>={};for(const [k,v] of Object.entries(full.series))if(JSON.stringify(v)!==JSON.stringify(prev[k]))replace[k]=v;const remove=Object.keys(prev).filter(k=>!(k in full.series));const delta={schema:1,base_revision:since,revision,as_of:full.as_of,replace,remove,full_etag:tag};const dtag='"d-'+since+'-'+revision+'"';return request.headers.get("If-None-Match")===dtag?response(null,304,{...headers,ETag:dtag}):response(delta,200,{...headers,ETag:dtag});}
 }
 return response(full,200,{...headers,ETag:tag});
}
export async function tick(env:Env,now:number,send:typeof fetch=fetch){
 if(env.RC_ENABLE_DISPATCH!=="1"||!env.RC_GITHUB_TOKEN)return {action:"disabled"};
 const claim=await acquire(env.DB,now);if(!claim)return {action:"skip"};
 try{const r=await send("https://api.github.com/repos/Okelii77/yandex-pulse/actions/workflows/pulse2-rc-dispatch.yml/dispatches",{method:"POST",redirect:"error",headers:{Authorization:"Bearer "+env.RC_GITHUB_TOKEN,Accept:"application/vnd.github+json","X-GitHub-Api-Version":"2022-11-28","User-Agent":"Pulse-RC","Content-Type":"application/json"},body:JSON.stringify({ref:"research/pulse-architecture-20261128",inputs:{slot:String(claim.slot),lease:claim.token}})});
 return {action:r.ok?"accepted":"uncertain_wait_for_expiry",slot:claim.slot};
 }catch{return {action:"uncertain_wait_for_expiry",slot:claim.slot};}
}
async function authorized(req:Request,env:Env){const token=req.headers.get("Authorization")||"";return env.RC_LOCAL_ONLY==="1"?!!env.LOCAL_TOKEN&&token==="Bearer "+env.LOCAL_TOKEN:token.startsWith("Bearer ")&&await githubOidcValid(token.slice(7));}
export default {
 async scheduled(_event:any,env:Env,ctx:any){ctx.waitUntil(Promise.all([tick(env,Date.now()),maintenance(env.DB,Date.now())]));},
 async fetch(req:Request,env:Env){
 const now=Date.now(),url=new URL(req.url),path=url.pathname;const cors:Record<string,string>=req.headers.get("Origin")===env.RC_ORIGIN&&env.RC_ORIGIN?{"Access-Control-Allow-Origin":env.RC_ORIGIN,"Access-Control-Allow-Headers":"Content-Type, If-None-Match","Access-Control-Allow-Methods":"GET, OPTIONS","Access-Control-Expose-Headers":"ETag, Retry-After","Vary":"Origin"}:{};
 try{
 if(req.method==="OPTIONS")return new Response(null,{status:204,headers:cors});
 if(req.method==="GET"&&path==="/api/health")return response({ok:true,version:"2.0.0-rc.1",trigger_ready:false},200,cors);
 if(req.method==="GET"&&path==="/api/status"){const row=await env.DB.prepare("SELECT revision,payload FROM rc_latest WHERE id=1").first();if(!row)return response({error:"waiting"},503,cors);const tag='"s-'+row.revision+'"';return req.headers.get("If-None-Match")===tag?response(null,304,{...cors,ETag:tag}):response(JSON.parse(row.payload),200,{...cors,ETag:tag});}
 if(req.method==="GET"&&path==="/api/history")return await history(env.DB,req,now,cors);
 if(req.method==="POST"&&(path==="/api/rc/acquire"||path==="/api/rc/ingest")){
 if(!await authorized(req,env))return response({error:"unauthorized"},401,cors);
 if(path.endsWith("acquire")){const claim=await acquire(env.DB,now);return response(claim||{error:"busy"},claim?200:409,cors);}
 const raw=await req.text();if(new TextEncoder().encode(raw).length>100000)return response({error:"too_large"},413,cors);
 const data=JSON.parse(raw);const ok=await publish(env.DB,data.claim,data.payload,now);return response({ok},ok?200:409,cors);}
 // Never expose or replace the existing production Ynison gate here.
 return response({error:"not_found"},404,cors);
 }catch{return response({error:"invalid_or_unavailable"},500,cors);}
 }
};
