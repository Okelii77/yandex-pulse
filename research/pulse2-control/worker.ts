 if(verifyOnly){
  const q=await env.DB.prepare("UPDATE rc_turnstile_probe SET state='running' WHERE id=1 AND state='armed' AND expires>? RETURNING id").bind(now).first();
  if(!q)return response({error:"trigger_not_configured"},503);
 }
