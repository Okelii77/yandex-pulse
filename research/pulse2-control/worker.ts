const DISPATCH_URL="https://api.github.com/repos/Okelii77/yandex-pulse/actions/workflows/pulse2-rc-dispatch.yml";
function githubHeaders(env:Env){return {Authorization:"Bearer "+env.RC_GITHUB_TOKEN,Accept:"application/vnd.github+json","X-GitHub-Api-Version":"2026-03-10","User-Agent":"YandexPulse-Scheduler/2.0","Content-Type":"application/json"};}
