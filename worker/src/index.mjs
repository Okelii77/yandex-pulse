/*
 * Yandex Pulse API — Cloudflare Workers + D1.
 * Open status and history, authenticated ingestion, Turnstile-protected manual
 * dispatch, global 10-minute cooldown. No service credentials reach the UI.
 */
const ORIGIN = "https://okelii77.github.io";
const RETENTION_DAYS = 90;
const COOLDOWN_MS = 10 * 60_000;
const MAX_PAYLOAD_BYTES = 100_000;

const json = (value, status=200, cors={}) => new Response(JSON.stringify(value), {
  status, headers: {"Content-Type": "application/json; charset=utf-8",
    "Cache-Control": "no-store", "X-Content-Type-Options": "nosniff", ...cors}
});
const corsHeaders = request => {
  const origin = request.headers.get("Origin");
  return origin === ORIGIN ? {
    "Access-Control-Allow-Origin": ORIGIN,
    "Access-Control-Allow-Methods": "GET, POST, OPTIONS",
    "Access-Control-Allow-Headers": "Content-Type",
    "Vary": "Origin"
  } : {};
};
const utc = value => typeof value === "string" && /^20\d{2}-\d\d-\d\dT\d\d:\d\d:\d\d/.test(value)
  && Number.isFinite(Date.parse(value));
const idOk = value => typeof value === "string" && /^[a-z][a-z0-9_-]{0,62}$/.test(value);
const limited = (value, max=160) => typeof value === "string" ? value.slice(0,max) : "";
const numberOrNull = n => Number.isFinite(n) && n >= 0 ? Math.round(n) : null;
const allowedStates = new Set(["ok","degraded","down","no_data","not_configured","disabled","cooldown","unknown"]);

// Do not trust a runner to decide which fields appear in a PUBLIC status JSON.
function safeStatus(input) {
  if (!input || !utc(input.generated_at) || !Array.isArray(input.results) ||
      !Array.isArray(input.checks) || !Array.isArray(input.categories) ||
      input.results.length > 150 || input.checks.length > 150 || input.categories.length > 30)
    throw new Error("invalid_snapshot");
  const categories = input.categories.filter(x=>idOk(x.id)).map(x=>({
    id:x.id,title:limited(x.title,80),description:limited(x.description,180),icon:limited(x.icon,32)
  }));
  const checks = input.checks.filter(x=>idOk(x.id)&&idOk(x.category)).map(x=>({
    id:x.id,category:x.category,name:limited(x.name,120),detail:limited(x.detail,240),
    kind:limited(x.kind,40),
    ...(typeof x.url === "string" && /^https:\/\/[a-z0-9.-]+\/[^@]*$/i.test(x.url) &&
       !/[?&#]/.test(x.url) ? {url: limited(x.url,250)} : {})
  }));
  const ids = new Set(checks.map(x=>x.id));
  const results = input.results.filter(x=>ids.has(x.id) && allowedStates.has(x.status) && utc(x.checked_at))
    .map(x=>{
      const row = {
        id:x.id,status:x.status,checked_at:x.checked_at,
        latency_ms:numberOrNull(x.latency_ms)
      };
      for (const prop of ["http_code","grpc_code","error_code","last_http_code","last_error_code"]) {
        if (Number.isInteger(x[prop]) && x[prop] >= 0 && x[prop] < 99999999999) row[prop]=x[prop];
      }
      // Reason/note are generated by our code from safe fixed strings. Keep short.
      for(const prop of ["reason","note","transport"]) {
        if(typeof x[prop]==="string") row[prop]=limited(x[prop],180);
      }
      if(utc(x.retry_after_at)) row.retry_after_at=x.retry_after_at;
      return row;
    });
  if(results.length !== input.results.length || results.length !== checks.length)
    throw new Error("incomplete_snapshot");
  return {
    schema:1,generated_at:input.generated_at,
    interval_minutes:30,
    scope:"Synthetic probes from GitHub Actions; NOT official Yandex service status.",
    categories,checks,results
  };
}

async function latest(env) {
  const row = await env.DB.prepare("SELECT payload FROM latest WHERE id=1").first();
  return row ? JSON.parse(row.payload) : null;
}

function cachesAllowed(request) {
  return request.method==="GET" && !request.headers.get("Authorization");
}

async function history(env) {
  const minTime = new Date(Date.now() - 30 * 86400_000).toISOString();
  const recent = new Date(Date.now() - 24 * 3600_000).toISOString();
  const week = new Date(Date.now() - 7 * 86400_000).toISOString();
  // Recent samples retain every check. Older ones are downsampled at 2h/6h
  // to keep the public D1 read budget manageable without hiding major errors.
  const {results} = await env.DB.prepare(
    "WITH ranked AS ( " +
      "SELECT check_id,checked_at,status,latency_ms, " +
      "ROW_NUMBER() OVER (PARTITION BY check_id, " +
      "CASE WHEN checked_at >= ? THEN 'r' || CAST(strftime('%s',checked_at)/1800 AS INT) " +
      "WHEN checked_at >= ? THEN 'w' || CAST(strftime('%s',checked_at)/7200 AS INT) " +
      "ELSE 'm' || CAST(strftime('%s',checked_at)/21600 AS INT) END " +
      "ORDER BY CASE WHEN status='down' THEN 0 WHEN status='degraded' THEN 1 ELSE 2 END, checked_at DESC) AS rn " +
      "FROM samples WHERE checked_at >= ? ) " +
      "SELECT check_id,checked_at,status,latency_ms FROM ranked WHERE rn=1 ORDER BY check_id,checked_at"
  ).bind(recent,week,minTime).all();
  const series={};
  for(const row of results || []) {
    if(!series[row.check_id])series[row.check_id]=[];
    series[row.check_id].push([row.checked_at,row.status,row.latency_ms]);
  }
  return {schema:1,retention_days:30,series};
}

/* GitHub Actions OIDC verifies caller identity without shared credentials. */
const b64url = input => {
  const str=input.replace(/-/g,"+").replace(/_/g,"/");
  const decoded=atob(str+"=".repeat((4-str.length%4)%4));
  return Uint8Array.from(decoded,c=>c.charCodeAt(0));
};
async function githubOidcValid(token) {
  try {
    if(!token || token.length>12000)return false;
    const parts=token.split(".");
    if(parts.length!==3)return false;
    const header=JSON.parse(new TextDecoder().decode(b64url(parts[0])));
    const claims=JSON.parse(new TextDecoder().decode(b64url(parts[1])));
    const seconds=Math.floor(Date.now()/1000);
    if(header.alg!=="RS256"||!header.kid||!Number.isInteger(claims.exp)||
       claims.exp<=seconds||claims.exp>seconds+600 ||
       claims.nbf>seconds || claims.iat>seconds+30 ||
       claims.iss!=="https://token.actions.githubusercontent.com" ||
       claims.aud!=="yandex-pulse-ingest" ||
       claims.repository!=="Okelii77/yandex-pulse" ||
       String(claims.repository_id)!=="1427282907" ||
       claims.ref!=="refs/heads/main" ||
       claims.workflow_ref!=="Okelii77/yandex-pulse/.github/workflows/pulse.yml@refs/heads/main")
      return false;
    const response=await fetch("https://token.actions.githubusercontent.com/.well-known/jwks",{
      cf:{cacheTtl:3600,cacheEverything:true}
    });
    if(!response.ok)return false;
    const jwks=await response.json();
    const jwk=(jwks.keys||[]).find(x=>x.kid===header.kid&&x.kty==="RSA"&&x.use==="sig");
    if(!jwk)return false;
    const key=await crypto.subtle.importKey("jwk",jwk,{name:"RSASSA-PKCS1-v1_5",hash:"SHA-256"},false,["verify"]);
    const signed=new TextEncoder().encode(parts[0]+"."+parts[1]);
    return crypto.subtle.verify({name:"RSASSA-PKCS1-v1_5"},key,b64url(parts[2]),signed);
  }catch{return false;}
}

async function ingest(request,env,cors) {
  const authorization=request.headers.get("Authorization") || "";
  const bearer=authorization.startsWith("Bearer ") ? authorization.slice(7) : "";
  const legacy=!!env.INGEST_TOKEN && authorization==="Bearer "+env.INGEST_TOKEN;
  const verified=legacy || await githubOidcValid(bearer);
  if (!verified) return json({error:"unauthorized"},401,cors);
  const length=Number(request.headers.get("Content-Length")||0);
  if(length>MAX_PAYLOAD_BYTES) return json({error:"payload_too_large"},413,cors);
  const raw=await request.text();
  if(raw.length>MAX_PAYLOAD_BYTES)return json({error:"payload_too_large"},413,cors);
  let data;
  try {data=safeStatus(JSON.parse(raw));} catch {return json({error:"bad_snapshot"},422,cors);}
  const measured=data.results.filter(x=>["ok","down","degraded","no_data"].includes(x.status))
    .map(x=>[x.id,x.checked_at,x.status,x.latency_ms]);
  const cutoff=new Date(Date.now()-RETENTION_DAYS*86400_000).toISOString();
  // One D1 batch = one transactional ingestion; json_each avoids 34 requests.
  await env.DB.batch([
    env.DB.prepare("INSERT INTO latest (id,generated_at,payload) VALUES (1,?,?) "+
      "ON CONFLICT(id) DO UPDATE SET generated_at=excluded.generated_at,payload=excluded.payload "+
      "WHERE excluded.generated_at>latest.generated_at").bind(data.generated_at,JSON.stringify(data)),
    env.DB.prepare("INSERT OR IGNORE INTO samples (check_id,checked_at,status,latency_ms) "+
      "SELECT json_extract(value,'$[0]'),json_extract(value,'$[1]'), "+
      "json_extract(value,'$[2]'),json_extract(value,'$[3]') FROM json_each(?)")
      .bind(JSON.stringify(measured)),
    env.DB.prepare("DELETE FROM samples WHERE checked_at < ?").bind(cutoff)
  ]);
  return json({ok:true,generated_at:data.generated_at,stored_samples:measured.length},200,cors);
}

async function checkTurnstile(token,env) {
  if(!env.TURNSTILE_SECRET || typeof token!=="string" || !token || token.length>2048)return false;
  const params=new URLSearchParams({secret:env.TURNSTILE_SECRET,response:token});
  const response=await fetch("https://challenges.cloudflare.com/turnstile/v0/siteverify",{
    method:"POST",headers:{"Content-Type":"application/x-www-form-urlencoded"},body:params.toString()
  });
  if(!response.ok)return false;
  const checked=await response.json();
  return checked.success===true && checked.hostname==="okelii77.github.io";
}

async function trigger(request,env,cors) {
  if(request.headers.get("Origin")!==ORIGIN) return json({error:"forbidden_origin"},403,cors);
  if(!env.GITHUB_ACTIONS_TOKEN || !env.TURNSTILE_SECRET)
    return json({error:"trigger_not_configured"},503,cors);
  let body;
  try {body=await request.json();}catch{return json({error:"invalid_json"},400,cors);}
  if(!(await checkTurnstile(body?.turnstileToken,env)))
    return json({error:"turnstile_failed"},403,cors);
  const now=Date.now(),oldest=now-COOLDOWN_MS;
  // Atomic global throttle prevents many visitors flooding Actions simultaneously.
  const gate = await env.DB.prepare(
    "INSERT INTO trigger_gate(key,last_started) VALUES('global',?) "+
    "ON CONFLICT(key) DO UPDATE SET last_started=excluded.last_started "+
    "WHERE trigger_gate.last_started<=? RETURNING last_started"
  ).bind(now,oldest).first();
  if(!gate) {
    const previous=await env.DB.prepare("SELECT last_started FROM trigger_gate WHERE key='global'").first();
    const remaining=Math.max(0,Math.ceil(((previous?.last_started||now)+COOLDOWN_MS-now)/1000));
    return json({error:"cooldown",retry_after_seconds:remaining},429,cors);
  }
  try {
    const response=await fetch(
      "https://api.github.com/repos/Okelii77/yandex-pulse/actions/workflows/pulse.yml/dispatches",
      {method:"POST",headers:{
        "Accept":"application/vnd.github+json",
        "Authorization":"Bearer "+env.GITHUB_ACTIONS_TOKEN,
        "X-GitHub-Api-Version":"2022-11-28",
        "User-Agent":"Yandex-Pulse-Trigger"
      },body:JSON.stringify({ref:"main"})}
    );
    if(!response.ok)throw Error("workflow_dispatch_failed");
    return json({ok:true,started_at:new Date(now).toISOString()},202,cors);
  }catch{
    // Release the slot if GitHub rejected the request. Never reveal response body.
    await env.DB.prepare("DELETE FROM trigger_gate WHERE key='global' AND last_started=?").bind(now).run();
    return json({error:"github_unavailable"},502,cors);
  }
}

export default {
  async fetch(request,env) {
    const cors=corsHeaders(request);
    const url=new URL(request.url);
    try {
      if(request.method==="OPTIONS") {
        return request.headers.get("Origin")===ORIGIN
          ? new Response(null,{status:204,headers:cors})
          : json({error:"forbidden_origin"},403,cors);
      }
      if(!env.DB)return json({error:"database_not_bound"},503,cors);
      if(url.pathname==="/api/health" && request.method==="GET")
        return json({ok:true,service:"yandex-pulse-api",version:1},200,cors);
      if(url.pathname==="/api/status" && request.method==="GET") {
        const data=await latest(env);
        return data ? json(data,200,cors) : json({error:"waiting_for_first_probe"},503,cors);
      }
      if(url.pathname==="/api/history" && request.method==="GET")return json(await history(env),200,cors);
      if(url.pathname==="/api/ingest" && request.method==="POST")return ingest(request,env,cors);
      if(url.pathname==="/api/trigger" && request.method==="POST")return trigger(request,env,cors);
      return json({error:"not_found"},404,cors);
    }catch {
      return json({error:"internal_error"},500,cors);
    }
  }
};
